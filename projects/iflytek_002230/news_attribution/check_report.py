mt = pd.read_csv(HERE / "news_matches.csv")

checks = []


def chk(name, claimed, actual, tol=0.0):
    ok = (claimed == actual) if tol == 0 else abs(claimed - actual) <= tol
    checks.append((name, claimed, actual, "OK" if ok else "MISMATCH"))


