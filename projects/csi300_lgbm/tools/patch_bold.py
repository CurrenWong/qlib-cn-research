"""把 build_post.py 里的「列表项开头的粗体」改成段落开头粗体。

原因（实测）：各平台的 markdown→HTML 转换在 **列表项第一格紧跟 ** 时会漏转，
粗体标记原样出现在正文里（CSDN 里还变成 \\*\\* 转义）。
规律：段落首的粗体正常；同一段里第二个及以后的粗体会漏；列表项开头的粗体会漏。

处理：
1) 导语 `> - **X** …` → `> **X** …`，条目之间用空引用行 `>` 分段（仍是引用块，每条独立成段）
2) 第十节的 `- **X** …` → 独立段落 `**X** …`
3) 生成后体检：不应再有「列表项 + **」的行
"""

import io
import re

P = r"D:\Project\qlib\projects\csi300_lgbm\tools\build_post.py"
s = io.open(P, encoding="utf-8").read()

# ---- 1) 导语：去掉列表符号，条目间加空引用行
lead_old = '''> - **排序信号是真的，但很弱。**'''
lead_new = '''> **排序信号是真的，但很弱。**'''
assert lead_old in s
s = s.replace(lead_old, lead_new)

# 导语其余条目："> - " → ">\n> "
s = re.sub(r"(?m)^> - ", ">\n> ", s)

# ---- 2) 第十节：列表项 → 独立段落
sec10_old = """- **把它当研究起点，不是买入清单。**先看这 20 只各自的公告、财报、订单和估值，本文的任何数据里都没有财务字段。
- **要上组合，先做减法。**上一版写的是"扩到 20-30 只、把调仓拉长到一个季度"——前半句保留（实测有效），后半句删掉（实测无效，见第六节）。正确做法是：**20 只 + 月度调仓 + 2 倍缓冲带**，每月只换掉跌出 top40 的那几只。
- **把成本算进去。**周度调仓的换手是月度的 3.5 倍；自建 20 只的方案测试期成本 {cost_yr*100:.1f}%/年，是策略超额的主要消耗项。
- **数据要跟到最新。**本次就因为成分股行情停在 10-27 而返工了一轮（见第一节数据陷阱）。"""
sec10_new = """**把它当研究起点，不是买入清单。**先看这 20 只各自的公告、财报、订单和估值，本文的任何数据里都没有财务字段。

**要上组合，先做减法。**上一版写的是"扩到 20-30 只、把调仓拉长到一个季度"——前半句保留（实测有效），后半句删掉（实测无效，见第六节）。正确做法是：20 只 + 月度调仓 + 2 倍缓冲带，每月只换掉跌出 top40 的那几只。

**把成本算进去。**周度调仓的换手是月度的 3.5 倍；自建 20 只的方案测试期成本 {cost_yr*100:.1f}%/年，是策略超额的主要消耗项。

**数据要跟到最新。**本次就因为成分股行情停在 10-27 而返工了一轮（见第一节数据陷阱）。"""
assert sec10_old in s
s = s.replace(sec10_old, sec10_new)

# ---- 3) 第四节的三个结论拆成三段（原来挤在一段里，第二个及以后的粗体会漏转）
q4_old = """**1. 排序信号可用，组合信号不可用。**分档结果说明模型确实能把"未来涨得好的"排在前面， 但把这个排序压缩成"10 只、月度调仓、等权"之后，算术超额被波动拖累与成本吃掉。 如果要继续做，方向是**更宽的持仓池**——这一点在第六节被实测证实；但同一句话里的“更长的持有期（季度调仓）”在第六节被我自己推翻。 **2. 单一切分不足以定论。**本次额外试了一个"指数跌破 MA60 空仓"的过滤变体： 验证期它更差（IR 0.21 vs 1.22）， 按协议（只在验证期选型）**不采用**；但它在测试期反而更好（年化 +8.76%）。 这既说明"一刀切"会错过东西，也说明单次切分的结论不该被当成定论——本次两边都如实写出来。 **3. 不要把模型输出当目标价。**表里的"预测 5 日收益"是回归输出，横截面可比、绝对值不可信， 也不是任何意义上的收益承诺。"""
q4_new = """**1. 排序信号可用，组合信号不可用。**分档结果说明模型确实能把"未来涨得好的"排在前面，但把这个排序压缩成"10 只、月度调仓、等权"之后，算术超额被波动拖累与成本吃掉。如果要继续做，方向是更宽的持仓池——这一点在第六节被实测证实；但同一句话里的"更长的持有期（季度调仓）"在第六节被我自己推翻。

**2. 单一切分不足以定论。**本次额外试了一个"指数跌破 MA60 空仓"的过滤变体：验证期它更差（IR 0.21 vs 1.22），按协议（只在验证期选型）不采用；但它在测试期反而更好（年化 +8.76%）。这既说明"一刀切"会错过东西，也说明单次切分的结论不该被当成定论——本次两边都如实写出来。

**3. 不要把模型输出当目标价。**表里的"预测 5 日收益"是回归输出，横截面可比、绝对值不可信，也不是任何意义上的收益承诺。"""
if q4_old in s:
    s = s.replace(q4_old, q4_new)
else:
    # 源串可能因换行/空格差异对不上：退化为在原句基础上做正则替换
    pat = re.compile(r"\*\*2\. 单一切分不足以定论。\*\*")
    s2 = pat.sub("\n\n**2. 单一切分不足以定论。**", s)
    pat3 = re.compile(r"\*\*3\. 不要把模型输出当目标价。\*\*")
    s2 = pat3.sub("\n\n**3. 不要把模型输出当目标价。**", s2)
    s = s2

# ---- 4) 体检：写文件前确认没有「列表项开头粗体」
s = s.replace('(POST / "article.md").write_text(out, encoding="utf-8")',
              '''bad = [ln for ln in out.splitlines() if re.match(r"^\\s*(>\\s*)?[-*+]\\s*\\*\\*", ln)]
if bad:
    raise SystemExit("仍有列表项开头的粗体:\\n" + "\\n".join(bad))
(POST / "article.md").write_text(out, encoding="utf-8")''')

io.open(P, "w", encoding="utf-8").write(s)
print("patched build_post.py")
